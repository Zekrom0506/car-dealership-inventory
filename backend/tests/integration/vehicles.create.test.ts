import request from 'supertest';
import { createApp } from '../../src/app';
import { prisma } from '../../src/lib/prisma';
import { resetDatabase, disconnectDatabase } from '../helpers/db';
import { createUser } from '../helpers/users';
import { authHeader } from '../helpers/auth';

const app = createApp();
/** Largest value a PostgreSQL INTEGER column can hold. */
const MAX_INT = 2_147_483_647;
const validVehicle = { make: 'Toyota', model: 'Corolla', category: 'Sedan', price: 20000, quantity: 5 };

/** Sends POST /api/vehicles as the given user (or with no token if user is omitted). */
const createVehicle = (body: object, user?: { id: number; role: 'USER' | 'ADMIN' }) => {
  const req = request(app).post('/api/vehicles');
  if (user) req.set('Authorization', authHeader(user));
  return req.send(body);
};

const createAdmin = () => createUser({ email: 'admin@example.com', role: 'ADMIN' });

beforeEach(resetDatabase);
afterAll(disconnectDatabase);

describe('POST /api/vehicles', () => {
  it('returns 201 with the new vehicle when called by an admin', async () => {
    const admin = await createAdmin();

    const response = await createVehicle(validVehicle, admin);

    expect(response.status).toBe(201);
    expect(response.body).toEqual({
      vehicle: {
        id: expect.any(Number),
        ...validVehicle,
        createdAt: expect.any(String),
        updatedAt: expect.any(String),
      },
    });
    expect(await prisma.vehicle.count()).toBe(1);
  });

  it('trims extra spaces from make and model', async () => {
    const admin = await createAdmin();

    const response = await createVehicle({ ...validVehicle, make: '  Toyota ', model: ' Corolla  ' }, admin);

    expect(response.status).toBe(201);
    expect(response.body.vehicle).toMatchObject({ make: 'Toyota', model: 'Corolla' });
  });

  it('accepts a quantity of 0 (a vehicle can be added before stock arrives)', async () => {
    const admin = await createAdmin();

    const response = await createVehicle({ ...validVehicle, quantity: 0 }, admin);

    expect(response.status).toBe(201);
    expect(response.body.vehicle.quantity).toBe(0);
  });

  it('accepts the largest allowed price and quantity (2147483647, the database integer limit)', async () => {
    const admin = await createAdmin();

    const response = await createVehicle({ ...validVehicle, price: MAX_INT, quantity: MAX_INT }, admin);

    expect(response.status).toBe(201);
    expect(response.body.vehicle).toMatchObject({ price: MAX_INT, quantity: MAX_INT });
  });

  it('ignores an id sent in the body (ids are generated by the database)', async () => {
    const admin = await createAdmin();

    const response = await createVehicle({ ...validVehicle, id: 999 }, admin);

    expect(response.status).toBe(201);
    expect(response.body.vehicle.id).not.toBe(999);
  });

  it('returns 401 without a token', async () => {
    const response = await createVehicle(validVehicle);

    expect(response.status).toBe(401);
    expect(await prisma.vehicle.count()).toBe(0);
  });

  it('returns 403 for a logged-in USER', async () => {
    const user = await createUser();

    const response = await createVehicle(validVehicle, user);

    expect(response.status).toBe(403);
    expect(await prisma.vehicle.count()).toBe(0);
  });

  const CATEGORY_MESSAGE = 'category must be one of: Sedan, SUV, Hatchback, Truck, Coupe, Convertible, Van';
  const PRICE_MESSAGE = 'price must be a positive whole number';
  const QUANTITY_MESSAGE = 'quantity must be a whole number of 0 or more';
  const { make: _m, ...withoutMake } = validVehicle;
  const { model: _mo, ...withoutModel } = validVehicle;
  const { category: _c, ...withoutCategory } = validVehicle;
  const { price: _p, ...withoutPrice } = validVehicle;
  const { quantity: _q, ...withoutQuantity } = validVehicle;

  it.each([
    ['make is missing', withoutMake, 'make is required'],
    ['make is only spaces', { ...validVehicle, make: '   ' }, 'make cannot be empty'],
    ['model is missing', withoutModel, 'model is required'],
    ['model is only spaces', { ...validVehicle, model: '   ' }, 'model cannot be empty'],
    ['category is missing', withoutCategory, 'category is required'],
    ['category is not in the fixed list', { ...validVehicle, category: 'Spaceship' }, CATEGORY_MESSAGE],
    ['category has the wrong case', { ...validVehicle, category: 'sedan' }, CATEGORY_MESSAGE],
    ['price is missing', withoutPrice, 'price is required'],
    ['price is 0', { ...validVehicle, price: 0 }, PRICE_MESSAGE],
    ['price is negative', { ...validVehicle, price: -100 }, PRICE_MESSAGE],
    ['price has decimals', { ...validVehicle, price: 19999.5 }, PRICE_MESSAGE],
    ['price is a string', { ...validVehicle, price: '20000' }, PRICE_MESSAGE],
    ['price is above the maximum', { ...validVehicle, price: MAX_INT + 1 }, 'price must be at most 2147483647'],
    ['quantity is missing', withoutQuantity, 'quantity is required'],
    ['quantity is negative', { ...validVehicle, quantity: -1 }, QUANTITY_MESSAGE],
    ['quantity has decimals', { ...validVehicle, quantity: 1.5 }, QUANTITY_MESSAGE],
    ['quantity is above the maximum', { ...validVehicle, quantity: MAX_INT + 1 }, 'quantity must be at most 2147483647'],
  ])('returns 400 when %s', async (_case, body, message) => {
    const admin = await createAdmin();

    const response = await createVehicle(body, admin);

    expect(response.status).toBe(400);
    expect(response.body).toEqual({ error: message });
    expect(await prisma.vehicle.count()).toBe(0);
  });
});
